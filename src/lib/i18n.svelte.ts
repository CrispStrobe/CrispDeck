// Language loaders — lazy-load non-English translations on demand
const languageLoaders: Record<string, () => Promise<any>> = {
  de: () => import('./i18n/de').then(m => m.default),
  fr: () => import('./i18n/fr').then(m => m.default),
  es: () => import('./i18n/es').then(m => m.default),
  ja: () => import('./i18n/ja').then(m => m.default),
  pt: () => import('./i18n/pt').then(m => m.default),
  zh: () => import('./i18n/zh').then(m => m.default),
  ar: () => import('./i18n/ar').then(m => m.default),
};

const loadedTranslations: Record<string, any> = {};

async function loadLanguage(lang: Language): Promise<any> {
  if (lang === 'en') return translations.en;
  if (loadedTranslations[lang]) return loadedTranslations[lang];
  const loader = languageLoaders[lang];
  if (!loader) return translations.en;
  const data = await loader();
  loadedTranslations[lang] = data;
  return data;
}


/** Deep merge: returns target with missing keys filled from fallback */
function deepMerge(target: any, fallback: any): any {
  const result: any = { ...fallback };
  for (const key of Object.keys(target)) {
    if (typeof target[key] === 'object' && target[key] !== null && typeof fallback[key] === 'object') {
      result[key] = deepMerge(target[key], fallback[key]);
    } else {
      result[key] = target[key];
    }
  }
  return result;
}

export class TranslationService {
  lang = $state<Language>('en');
  private _langData = $state<any>(null);
  t = $derived(
    this.lang === 'en'
      ? translations.en
      : this._langData
        ? deepMerge(this._langData, translations.en)
        : translations.en  // fallback to English while loading
  );
  isRtl = $derived(RTL_LANGUAGES.includes(this.lang));
  dir = $derived(RTL_LANGUAGES.includes(this.lang) ? 'rtl' as const : 'ltr' as const);

  constructor() {
    if (typeof localStorage !== 'undefined') {
      const saved = localStorage.getItem('crispdeck-language') as Language;
      if (saved && saved !== 'en') {
        this.lang = saved;
        // Load the saved language asynchronously
        loadLanguage(saved).then(data => { this._langData = data; });
      }
    }
  }

  setLanguage(l: Language) {
    this.lang = l;
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem('crispdeck-language', l);
    }
    // Update document direction for RTL support
    if (typeof document !== 'undefined') {
      document.documentElement.dir = RTL_LANGUAGES.includes(l) ? 'rtl' : 'ltr';
    }
    // Load translation data
    if (l === 'en') {
      this._langData = null;
    } else {
      loadLanguage(l).then(data => { this._langData = data; });
    }
  }
}

export const i18n = new TranslationService();
