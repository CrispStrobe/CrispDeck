#!/usr/bin/env node
/**
 * Generate TESTING.md from the source.
 *
 * PLAN item 174 — a day of real use with real accounts — is the highest-value
 * thing left, and the one nobody can automate. What *can* be automated is
 * making sure the list you work through is the real list: twenty column types
 * and not the fourteen someone remembers, every route and not the ones that
 * come to mind, every shortcut the help dialog claims to offer.
 *
 * deck.test.ts once asserted "supports all 14 column types" while the app had
 * grown to 20. A checklist written by hand goes stale the same way, except
 * quietly, because nothing runs it.
 *
 *   node scripts/testing-checklist.mjs          # write TESTING.md
 *   node scripts/testing-checklist.mjs --check  # fail if it is out of date
 */
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { pathToFileURL } from 'node:url';

/**
 * The repo root, found by walking up from the working directory.
 *
 * Deriving it from `import.meta.url` broke when the guard test imported this
 * under Vite, which rewrites that to an `/@fs/...` URL — the paths resolved to
 * a directory that does not exist and every read threw ENOENT.
 */
function repoRoot() {
  let dir = process.cwd();
  for (let i = 0; i < 10; i++) {
    if (existsSync(join(dir, 'package.json'))) return dir;
    const up = dirname(dir);
    if (up === dir) break;
    dir = up;
  }
  return process.cwd();
}

const ROOT = repoRoot();
const OUT = join(ROOT, 'TESTING.md');

function read(path) {
  return readFileSync(join(ROOT, path), 'utf-8');
}

/** The runtime array, not the type — so this cannot drift from the app. */
export function columnTypes() {
  const src = read('src/lib/deck-columns.ts');
  const block = src.match(/export const COLUMN_TYPES = \[([\s\S]*?)\] as const;/);
  if (!block) throw new Error('COLUMN_TYPES not found in src/lib/deck-columns.ts');
  return [...block[1].matchAll(/'([^']+)'/g)].map((m) => m[1]);
}

export function queryRequired() {
  const src = read('src/lib/deck-columns.ts');
  const block = src.match(/QUERY_REQUIRED_COLUMN_TYPES[^=]*= \[([\s\S]*?)\];/);
  return block ? [...block[1].matchAll(/'([^']+)'/g)].map((m) => m[1]) : [];
}

export function routes() {
  const base = join(ROOT, 'src/routes');
  const found = [];
  (function walk(dir) {
    for (const entry of readdirSync(dir)) {
      const full = join(dir, entry);
      if (statSync(full).isDirectory()) walk(full);
      else if (entry === '+page.svelte') {
        const path = '/' + relative(base, dir).replace(/\\/g, '/');
        found.push(path === '/.' ? '/' : path);
      }
    }
  })(base);
  return found.sort();
}

export function shortcuts() {
  const src = read('src/lib/components/KeyboardShortcuts.svelte');
  const block = src.match(/const shortcuts = \[([\s\S]*?)\n  \];/);
  if (!block) throw new Error('shortcut list not found in KeyboardShortcuts.svelte');
  const sections = [];
  for (const m of block[1].matchAll(/\{ section: '([^']+)', items: \[([\s\S]*?)\]\}/g)) {
    sections.push({
      name: m[1],
      items: [...m[2].matchAll(/\{ key: '([^']+)', desc: '([^']+)' \}/g)].map((i) => ({
        key: i[1],
        desc: i[2],
      })),
    });
  }
  return sections;
}

function render() {
  const types = columnTypes();
  const needsQuery = new Set(queryRequired());
  const lines = [];

  lines.push('# CrispDeck — testing checklist');
  lines.push('');
  lines.push('> Generated by `scripts/testing-checklist.mjs` from the source, and');
  lines.push('> pinned by `src/lib/testing-checklist.test.ts`. Do not edit by hand:');
  lines.push('> add a column type or a route and regenerate, or the guard fails.');
  lines.push('');
  lines.push('This is PLAN item 174 — connect real accounts and use the app for a day.');
  lines.push('It is the highest-value work left and the part no test can do. Errors');
  lines.push('swallowed along the way land in the in-app log viewer, which has a');
  lines.push('download button; export it at the end and the session leaves evidence');
  lines.push('rather than impressions.');
  lines.push('');
  lines.push('For each item: does it work, is it confusing, would you use it?');
  lines.push('');

  lines.push(`## Deck column types (${types.length})`);
  lines.push('');
  lines.push('Add one of each to a deck with real accounts connected.');
  lines.push('');
  for (const t of types) {
    lines.push(`- [ ] \`${t}\`${needsQuery.has(t) ? ' — needs a query; try an empty one too' : ''}`);
  }
  lines.push('');

  lines.push('## Column management');
  lines.push('');
  for (const item of [
    'Add a column, reload, it is still there',
    'Remove a column, reload, it is still gone',
    'Reorder columns by drag, reload, the order held',
    'Resize a column to each end of its range (280–600px)',
    'A column whose account was disconnected — what does it say?',
  ]) {
    lines.push(`- [ ] ${item}`);
  }
  lines.push('');

  const sections = shortcuts();
  const total = sections.reduce((n, s) => n + s.items.length, 0);
  lines.push(`## Keyboard shortcuts (${total})`);
  lines.push('');
  lines.push('Every one the help dialog (`?`) claims to offer.');
  lines.push('');
  for (const section of sections) {
    lines.push(`### ${section.name}`);
    lines.push('');
    for (const item of section.items) {
      lines.push(`- [ ] \`${item.key}\` — ${item.desc}`);
    }
    lines.push('');
  }

  const paths = routes();
  lines.push(`## Routes (${paths.length})`);
  lines.push('');
  lines.push('Reachable, renders with real data, and reachable *from the UI* —');
  lines.push('a route only findable by typing the URL is a route nobody uses.');
  lines.push('');
  for (const p of paths) {
    lines.push(`- [ ] \`${p}\``);
  }
  lines.push('');

  lines.push('## Flows that cross pages');
  lines.push('');
  for (const item of [
    'Reply from the deck: does the floating compose carry the right context?',
    'Quote from the deck, then check the posted quote renders',
    'Crosspost one draft to Bluesky and Mastodon, confirm both landed',
    'Crosspost where one platform fails — does the history say "partial"?',
    'Two Bluesky accounts and one Mastodon: is it ever unclear which is acting?',
    'Go offline mid-session: feed, notifications and trending should say so',
    'Come back online: the banners should clear on their own',
    'Install as a PWA, kill the network, open it cold',
  ]) {
    lines.push(`- [ ] ${item}`);
  }
  lines.push('');

  lines.push('## At the end');
  lines.push('');
  lines.push('- [ ] Export the log viewer and keep the file');
  lines.push('- [ ] Three things that were confusing');
  lines.push('- [ ] Three things that were broken');
  lines.push('- [ ] Three things you never once wanted');
  lines.push('');

  return lines.join('\n');
}

// Only act when run as a script. Without this guard, importing the module to
// reuse columnTypes()/routes() — which the guard test does — would overwrite
// TESTING.md as a side effect of the import.
const runDirectly =
  process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;

if (runDirectly && process.argv.includes('--check')) {
  const generated = render();
  let current = '';
  try {
    current = readFileSync(OUT, 'utf-8');
  } catch {
    /* missing counts as out of date */
  }
  if (current !== generated) {
    console.error('TESTING.md is out of date — run: node scripts/testing-checklist.mjs');
    process.exit(1);
  }
  console.log('TESTING.md is up to date.');
} else if (runDirectly) {
  const generated = render();
  writeFileSync(OUT, generated);
  console.log(`Wrote TESTING.md — ${columnTypes().length} column types, ${routes().length} routes.`);
}

export { render };
