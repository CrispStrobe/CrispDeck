import { createCanvas, Image } from '@napi-rs/canvas';
import { readFileSync, writeFileSync } from 'fs';
import { join } from 'path';

const srcDir = join(process.cwd(), 'static');
const tauriDir = join(process.cwd(), 'src-tauri', 'icons');

// Read the 1024px source icon
const srcBuf = readFileSync(join(srcDir, 'icon-1024.png'));
const img = new Image();
img.src = srcBuf;

function resize(size, filename) {
  const canvas = createCanvas(size, size);
  const ctx = canvas.getContext('2d');
  ctx.drawImage(img, 0, 0, size, size);
  writeFileSync(join(tauriDir, filename), canvas.toBuffer('image/png'));
  console.log(`  ${filename} (${size}x${size})`);
}

console.log('Generating Tauri icons:');
resize(32, '32x32.png');
resize(128, '128x128.png');
resize(256, '128x128@2x.png');
resize(1024, 'icon.png');  // 1024px required — Tauri generates iOS AppIcon.appiconset from this

// For .icns and .ico we just copy the PNG — Tauri's build will handle conversion
console.log('Done! Note: .icns and .ico will be generated by Tauri build.');
console.log('Run `npx tauri icon src-tauri/icons/icon.png` to regenerate all platform icons.');
